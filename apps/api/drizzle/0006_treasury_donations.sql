-- The only shape the public API reads (data-model.md §4.1): published rows,
-- public columns, and the description only once the entry is qualified. The
-- API also filters on `livemode` (Stripe test rows never reach production
-- pages); `adjusts_entry_id` lets the statistics net refunds and disputes.
CREATE VIEW "treasury_public_entries" AS
  SELECT "id", "entry_number", "entry_type", "currency", "gross_amount", "net_amount", "cadence",
         "occurred_on", "occurred_at", "published_at", "review_status_key", "recurrence_id",
         "adjusts_entry_id", "source", "livemode",
         CASE WHEN "review_status_key" IN ('qualified', 'not_required') THEN "public_description" END AS "public_description"
  FROM "treasury_entries"
  WHERE "publication_status" = 'published';

-- Cross-row rules (data-model.md §4.1 rule 5): refunds and dispute
-- adjustments adjust a donation of the same currency, in the same Stripe
-- mode; together they never take more than the donation; disputes never give
-- back more than they withdrew. A donation with adjustments keeps its type,
-- currency and amount; only expenses carry expense types.
CREATE FUNCTION "treasury_entries_integrity"() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  target record;
  adjusted bigint;
  disputed bigint;
BEGIN
  IF NEW.entry_type IN ('refund', 'dispute') THEN
    SELECT entry_type, currency, gross_amount, livemode INTO target FROM treasury_entries WHERE id = NEW.adjusts_entry_id FOR UPDATE;
    IF target.entry_type IS DISTINCT FROM 'donation' THEN
      RAISE EXCEPTION 'A refund or dispute must adjust a donation.' USING ERRCODE = 'check_violation';
    END IF;
    IF target.currency <> NEW.currency THEN
      RAISE EXCEPTION 'A refund or dispute must be in the currency of its donation.' USING ERRCODE = 'check_violation';
    END IF;
    IF target.livemode <> NEW.livemode THEN
      RAISE EXCEPTION 'A refund or dispute must be in the Stripe mode of its donation.' USING ERRCODE = 'check_violation';
    END IF;
    SELECT coalesce(sum(gross_amount), 0) INTO adjusted FROM treasury_entries
      WHERE adjusts_entry_id = NEW.adjusts_entry_id AND id <> NEW.id;
    IF target.gross_amount + adjusted + NEW.gross_amount < 0 THEN
      RAISE EXCEPTION 'Refunds and disputes cannot exceed the donation.' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.entry_type = 'dispute' THEN
      SELECT coalesce(sum(gross_amount), 0) INTO disputed FROM treasury_entries
        WHERE adjusts_entry_id = NEW.adjusts_entry_id AND entry_type = 'dispute' AND id <> NEW.id;
      IF disputed + NEW.gross_amount > 0 THEN
        RAISE EXCEPTION 'A dispute cannot give back more than was withdrawn.' USING ERRCODE = 'check_violation';
      END IF;
    END IF;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.entry_type = 'donation'
     AND (NEW.entry_type, NEW.currency, NEW.gross_amount, NEW.livemode) IS DISTINCT FROM (OLD.entry_type, OLD.currency, OLD.gross_amount, OLD.livemode)
     AND EXISTS (SELECT 1 FROM treasury_entries WHERE adjusts_entry_id = OLD.id) THEN
    RAISE EXCEPTION 'A refunded donation keeps its type, currency and amount.' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.entry_type = 'expense' AND NEW.entry_type <> 'expense'
     AND EXISTS (SELECT 1 FROM treasury_entry_expense_types WHERE entry_id = OLD.id) THEN
    RAISE EXCEPTION 'Remove the expense types before changing the entry type.' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
